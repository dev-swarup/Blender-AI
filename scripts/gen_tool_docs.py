from __future__ import annotations

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import devimport

devimport.install()

from blender_ai.agent import roles
from blender_ai.tools import catalog
from blender_ai.tools.registry import GROUP_ORDER, ToolKind, ToolSpec

GROUP_TITLES = {
    "meta": "Meta",
    "agents": "Sub-agents",
    "scene": "Scene",
    "objects": "Objects",
    "mesh": "Mesh editing",
    "modifiers": "Modifiers",
    "uv": "UVs",
    "materials": "Materials",
    "textures": "Textures (PBR)",
    "lights_camera": "Lights and cameras",
    "world": "World",
    "render": "Render and viewport",
    "rigging": "Rigging",
    "animation": "Animation",
    "procedural": "Procedural (geometry nodes)",
    "physics": "Physics",
    "integrations": "Helper add-ons",
    "mcp": "MCP servers",
}

LIST_ITEM = re.compile(r"^\s*(?:[-*]|\d+[.)])\s")


def _slug(title: str) -> str:
    return re.sub(r"\s", "-", re.sub(r"[^a-z0-9 -]", "", title.lower()))


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _type(schema: dict) -> str:
    t = schema.get("type", "any")
    if isinstance(t, list):
        return " / ".join(t)
    if t == "array":
        items = schema.get("items", {})
        n = schema.get("minItems")
        return f"{n} numbers" if n and n == schema.get("maxItems") and items.get("type") == "number" else f"list of {_type(items)}"
    return " \\| ".join(f"`{v}`" for v in schema["enum"]) if "enum" in schema else t


def _paragraphs(text: str) -> str:
    out: list[str] = []
    for line in text.strip().splitlines():
        if out and line.strip() and out[-1].strip() and not LIST_ITEM.match(line) and not out[-1].startswith("```"):
            out[-1] += " " + line.strip()
        else:
            out.append(line.rstrip())
    return "\n".join(out)


def _summary(spec: ToolSpec) -> str:
    flat = " ".join(spec.description.split())
    match = re.match(r"(.+?(?<!e\.g)(?<!i\.e)[.!?])(?=\s+[A-Z]|$)", flat)
    return match.group(1) if match else flat


def _flags(spec: ToolSpec) -> list[str]:
    flags = []
    if spec.requires:
        flags.append(f"needs {spec.requires}")
    if spec.destructive:
        flags.append("destructive")
    if spec.kind is ToolKind.ASYNC:
        flags.append("async")
    if spec.kind is ToolKind.APPROVAL:
        flags.append("approval")
    if spec.kind is ToolKind.QUESTION:
        flags.append("asks the user")
    if spec.kind is ToolKind.AGENT:
        flags.append("sub-agents")
    return flags


def _agents_table(present: set[str]) -> list[str]:
    names = [roles.info(mode) for mode in roles.ORDER]
    lines = ["| Group | " + " | ".join(f"{r.name} ({r.label})" for r in names) + " |"]
    lines.append("|---|" + ":---:|" * len(names))
    for group in GROUP_ORDER:
        title = f"[{GROUP_TITLES[group]}](#{_slug(GROUP_TITLES[group])})" if group in present else GROUP_TITLES[group]
        lines.append(f"| {title} | " + " | ".join("●" if group in r.groups else "" for r in names) + " |")
    return lines


def _parameters(spec: ToolSpec) -> list[str]:
    props = spec.input_schema.get("properties", {})
    if not props:
        return ["*No parameters.*", ""]
    required = set(spec.input_schema.get("required", []))
    lines = ["| Parameter | Type | Required | Description |", "|---|---|:---:|---|"]
    for name, schema in props.items():
        desc = _cell(schema.get("description") or "")
        if "default" in schema:
            desc += f" Default: `{schema['default']}`."
        lines.append(f"| `{name}` | {_type(schema)} | {'yes' if name in required else ''} | {desc.strip()} |")
    return [*lines, ""]


def main() -> None:
    registry = catalog.load()
    specs = sorted([*registry.specs(), roles.SPAWN_SPEC], key=lambda s: (GROUP_ORDER.index(s.group), s.name))
    groups = [(g, [s for s in specs if s.group == g]) for g in GROUP_ORDER]
    groups = [(g, items) for g, items in groups if items]
    lines = [
        "# Tool reference",
        "",
        "> Generated by `scripts/gen_tool_docs.py` from the tool registry. Do not edit by hand.",
        "",
        (
            f"Blender AI exposes {len(specs)} built-in tools to its agents. Each tool has a JSON schema, is validated before it runs and "
            "executes on Blender's main thread as one undo step. Sub-agents and MCP servers extend the set at run time."
        ),
        "",
        "## Contents",
        "",
        "- [Toolsets by agent](#toolsets-by-agent)",
        "- [Conventions](#conventions)",
        *[f"- [{GROUP_TITLES[g]}](#{_slug(GROUP_TITLES[g])}) ({len(items)})" for g, items in groups],
        "",
        "## Toolsets by agent",
        "",
        (
            "Each tab is an agent with its own system prompt and toolset. All of them share one conversation, and every agent can call "
            "`run_python` (full `bpy` access) and `spawn_agents`, so none is limited to its toolset."
        ),
        "",
        *_agents_table({g for g, _ in groups}),
        "",
        "## Conventions",
        "",
        "- **needs `<helper>`**: the tool is offered only while that helper add-on is installed and enabled.",
        "- **destructive**: the tool deletes or overwrites data. Each call is still a single undo step.",
        "- **async**: the slow part runs off the main thread, such as image generation, downloads and MCP calls.",
        "- **approval**: the user is asked first when *Ask before running Python* is on.",
        "- **asks the user**: the run pauses until the user answers.",
        "- **sub-agents**: starts specialist agents that work concurrently in the same scene.",
        f"- Sub-agents nest up to {roles.MAX_DEPTH} levels, run {roles.DEFAULT_PARALLEL} at a time by default (up to {roles.MAX_PARALLEL} in settings) and are capped at {roles.MAX_SUBAGENTS_PER_REQUEST} per request. They do not receive "
        + " or ".join(f"`{n}`" for n in sorted(roles.SUBAGENT_EXCLUDED))
        + ".",
        "- Tools from connected MCP servers are named `<server>_<tool>` and are added to every agent. They are not listed here.",
        "",
    ]
    for group, items in groups:
        lines += [f"## {GROUP_TITLES[group]}", "", "| Tool | Summary | Notes |", "|---|---|---|"]
        lines += [f"| [`{s.name}`](#{s.name}) | {_cell(_summary(s))} | {', '.join(_flags(s))} |" for s in items]
        lines.append("")
        for spec in items:
            flags = _flags(spec)
            lines += [f"### {spec.name}", ""]
            if flags:
                lines += [f"*{' · '.join(flags)}*", ""]
            lines += [_paragraphs(spec.description), "", *_parameters(spec)]
    out = os.path.join(ROOT, "docs", "tools.md")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    print(f"wrote {out} ({len(specs)} tools)")


main()
